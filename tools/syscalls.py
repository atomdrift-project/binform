"""Generate src/syscalls.rs, Linux syscall names by architecture, from the
`libc` crate's glibc tables.

    python -I tools/syscalls.py LIBC_CRATE_DIR > src/syscalls.rs
"""
import os
import re
import sys

LIBC = sys.argv[1]
VERSION = os.path.basename(os.path.normpath(LIBC))
GNU = "src/unix/linux_like/linux/gnu/"

# binform table name -> (the Arch variants it serves, libc file).
TABLES = [
    ("X86_64", ["X86_64"], "b64/x86_64/not_x32.rs"),
    ("X86", ["X86"], "b32/x86/mod.rs"),
    ("ARM64", ["Arm64"], "b64/aarch64/mod.rs"),
    ("ARM", ["Arm"], "b32/arm/mod.rs"),
    ("MIPS", ["Mips", "MipsEl", "MipsR6", "MipsR6El"], "b32/mips/mod.rs"),
    ("MIPS64", ["Mips64", "Mips64El", "Mips64R6", "Mips64R6El"], "b64/mips64/mod.rs"),
    ("POWERPC", ["PowerPc"], "b32/powerpc.rs"),
    ("POWERPC64", ["PowerPc64", "PowerPc64El"], "b64/powerpc64/mod.rs"),
    ("S390X", ["S390x"], "b64/s390x.rs"),
    ("SPARC", ["Sparc"], "b32/sparc/mod.rs"),
    ("SPARC64", ["Sparc64"], "b64/sparc64/mod.rs"),
    ("RISCV32", ["RiscV32"], "b32/riscv32/mod.rs"),
    ("RISCV64", ["RiscV64"], "b64/riscv64/mod.rs"),
    ("LOONGARCH64", ["LoongArch64"], "b64/loongarch64/mod.rs"),
    ("M68K", ["M68k"], "b32/m68k/mod.rs"),
    ("CSKY", ["CSky"], "b32/csky/mod.rs"),
]

CONST = re.compile(r"pub const SYS_(\w+):\s*\w+\s*=\s*([0-9+ ]+);")


def table(path):
    names = {}
    with open(os.path.join(LIBC, GNU, path), encoding="utf-8") as f:
        for name, expr in CONST.findall(f.read()):
            number = sum(int(term) for term in expr.split("+"))
            # The first name wins over a later alias of the same number.
            names.setdefault(number, name)
    return sorted(names.items())


out = []
w = out.append
w("//! Linux syscall names by architecture: what a number in the syscall")
w("//! register means. Generated by `tools/syscalls.py` from the glibc tables")
w(f"//! of the `libc` crate ({VERSION}); do not edit.")
w("")
w("use crate::Arch;")
w("")
w("/// The `(number, name)` table for `arch`, or `None` for an architecture")
w("/// this does not name.")
w("fn table(arch: Arch) -> Option<&'static [(u16, &'static str)]> {")
w("    Some(match arch {")
for const, arches, _ in TABLES:
    w(f"        {' | '.join('Arch::' + a for a in arches)} => &{const},")
w("        _ => return None,")
w("    })")
w("}")
w("")
w("/// The name Linux gives syscall `number` on `arch`.")
w("pub(crate) fn name(arch: Arch, number: u64) -> Option<&'static str> {")
w("    let table = table(arch)?;")
w("    let number = u16::try_from(number).ok()?;")
w("    let index = table.binary_search_by_key(&number, |&(n, _)| n).ok()?;")
w("    table.get(index).map(|&(_, name)| name)")
w("}")
w("")
w("/// The number Linux gives syscall `name` on `arch`: the inverse of")
w("/// [`name`], for resolving a libc wrapper such as `connect` to the call")
w("/// it issues. The tables are keyed by number, so this scans.")
w("pub(crate) fn number(arch: Arch, name: &str) -> Option<u64> {")
w("    table(arch)?.iter().find(|&&(_, n)| n == name).map(|&(number, _)| u64::from(number))")
w("}")
for const, _, path in TABLES:
    rows = table(path)
    assert rows and all(n < 65536 for n, _ in rows), path
    w("")
    w(f"/// `{GNU}{path}`")
    w("#[rustfmt::skip]")
    w(f"static {const}: [(u16, &str); {len(rows)}] = [")
    line = "   "
    for n, name in rows:
        item = f' ({n}, "{name}"),'
        if len(line) + len(item) > 99:
            w(line)
            line = "   "
        line += item
    w(line)
    w("];")
sys.stdout.write("\n".join(out) + "\n")
